//! Assertions for NFR-002 headers on generated Rust artifacts.

/// Checks the leading header of one emitted Rust file, including each input identity it renders.
pub(super) fn assert_header(path: &str, source: &str, subjects: &[&str]) {
    assert!(path.ends_with(".rs"), "expected a Rust artifact: {path}");
    let header = source
        .lines()
        .take_while(|line| !line.is_empty())
        .collect::<Vec<_>>()
        .join("\n");
    let generator = "// @generated by quire-contract-codegen";
    let spdx = "// SPDX-License-Identifier: MIT OR Apache-2.0";
    let valid = |text: &str| {
        text.contains(generator)
            && text.contains(spdx)
            && subjects.iter().all(|subject| text.contains(subject))
    };
    assert!(
        valid(&header),
        "{path} lacks a required header identity: {}",
        header.lines().take(8).collect::<Vec<_>>().join("\n")
    );

    // Mutation controls prove this assertion rejects each kind of missing header evidence.
    assert!(
        !valid(&header.replacen(generator, "", 1)),
        "{path} accepted a missing generator"
    );
    assert!(
        !valid(&header.replacen(spdx, "", 1)),
        "{path} accepted a missing SPDX line"
    );
    if let Some(subject) = subjects.last() {
        assert!(
            !valid(&header.replace(subject, "")),
            "{path} accepted a missing subject"
        );
    }
}
