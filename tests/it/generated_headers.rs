//! Assertions for NFR-002 headers on generated Rust artifacts.

/// Checks the leading header of one emitted Rust file, including each input identity it renders.
pub(super) fn assert_header(path: &str, source: &str, subjects: &[&str]) {
    assert!(path.ends_with(".rs"), "expected a Rust artifact: {path}");
    let header = source
        .lines()
        .take_while(|line| !line.is_empty())
        .collect::<Vec<_>>()
        .join("\n");
    assert!(
        header.contains("// @generated by quire-contract-codegen"),
        "{path} lacks generator identity in its header: {header}"
    );
    assert!(
        header.contains("// SPDX-License-Identifier: MIT OR Apache-2.0"),
        "{path} lacks its SPDX identity in the header: {header}"
    );
    for subject in subjects {
        assert!(
            header.contains(subject),
            "{path} lacks input identity {subject:?} in its header: {header}"
        );
    }
}
