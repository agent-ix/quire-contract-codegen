//! Native-only original composite artifact authentication (FR-033-AC-18).
//! No backend proof, shadow result, pair count or falsified settlement is manufactured here.
use super::function::{LockedSource, ReplayInputs};
use crate::{
    Artifact, CompositeBuildError, CompositeEqualityOracles, OriginalCompositeEqContext,
    OriginalCompositeEqRequest,
};
use qsl_replay::{
    CompositeParityClaim, ParityPreimage, ReplayLimits, ReplayRequestWire, WitnessValue,
};
use quire_contract_model::{CheckedNodeId, CheckedOccurrence, CheckedPackageV2};
use std::sync::Arc;

/// A generator-backed original composite body plus complete immutable generated byte set.
/// Driver-owned native execution remains outside CG.
#[derive(Debug)]
pub struct OriginalCompositeArtifactBinding {
    request: OriginalCompositeEqRequest,
    origin: Arc<crate::oracle::equality::CompositeGenerationOrigin>,
    inputs: Arc<ReplayInputs>,
    operands: [WitnessValue; 2],
    oracle_symbol: String,
    environment_symbol: String,
}

impl OriginalCompositeEqContext {
    /// Retain one genuine composite generation and original positional claim before execution.
    /// Existing verified construction still needs no native observation. This separate native-only
    /// binding supplies no backend, shadow or pair-count evidence (IR-806 remains gated).
    ///
    /// # Errors
    /// Refuses stale/absent generator authority, another original package or an invalid body.
    pub fn retain_generated_artifact(
        &self,
        generated: &CompositeEqualityOracles,
        node: &CheckedNodeId,
        occurrence: &CheckedOccurrence,
        operator: qsl_replay::EqualityOperator,
        harness_bounds: &[qsl_replay::ProofBound],
        operands: [WitnessValue; 2],
        work_limit: u64,
    ) -> Result<OriginalCompositeArtifactBinding, CompositeBuildError> {
        let origin = generated.replay_origin().map_err(|cause| match cause {
            crate::oracle::equality::CompositeOriginRefusal::Unavailable => {
                CompositeBuildError::GeneratedAuthorityUnavailable
            }
            crate::oracle::equality::CompositeOriginRefusal::Changed => {
                CompositeBuildError::GeneratedArtifactChanged
            }
        })?;
        if origin.original.as_ref() != self.original_context().original.as_ref() {
            return Err(CompositeBuildError::ContextMismatch);
        }
        let packet = self.parity_packet(node, occurrence, operator, harness_bounds, work_limit)?;
        let request = self.request_from_packet(
            packet,
            node,
            occurrence,
            operator,
            harness_bounds,
            work_limit,
        )?;
        let operator_kind = match operator {
            qsl_replay::EqualityOperator::Equal => crate::EqualityOperatorKind::Equal,
            qsl_replay::EqualityOperator::NotEqual => crate::EqualityOperatorKind::NotEqual,
        };
        let [left, right] = request.operands().operands.as_slice() else {
            return Err(CompositeBuildError::OperandShape);
        };
        let mut candidates = generated.claim_map.items.iter().filter_map(|claim| {
            let crate::ClaimDisposition::Generated(item) = &claim.result else {
                return None;
            };
            (&claim.node_id == node
                && item.descriptor.operator == operator_kind
                && item.descriptor.left_source_type == left.semantic_type
                && item.descriptor.right_source_type == right.semantic_type
                && item.descriptor.left_conversion_target.is_none()
                && item.descriptor.right_conversion_target.is_none())
            .then_some(item)
        });
        let selected = candidates
            .next()
            .ok_or(CompositeBuildError::UnsupportedNodeOperation)?;
        if candidates.next().is_some() {
            return Err(CompositeBuildError::UnsupportedNodeOperation);
        }
        let oracle_symbol = selected.oracle_symbol.clone();
        let environment_symbol = selected.environment_symbol.clone();
        Ok(OriginalCompositeArtifactBinding {
            request,
            origin: Arc::clone(origin),
            inputs: Arc::clone(&self.original_context().inputs),
            operands,
            oracle_symbol,
            environment_symbol,
        })
    }
}

/// Actual driver observation, independently captured after executing the emitted oracle bytes.
/// Honest execution is the declared driver trust boundary; this is not an unforgeable Kani receipt.
#[derive(Clone, Debug)]
pub struct CompositeDriverObservation {
    /// Every original generated path and its actual staged bytes, read back after execution.
    pub staged_entries: Vec<(String, Vec<u8>)>,
    /// Actual generated oracle entry invoked by the driver.
    pub oracle_symbol: String,
    /// Actual prepared environment constructor invoked by the driver.
    pub environment_symbol: String,
    /// Actual two operands, in source position order.
    pub operands: [WitnessValue; 2],
    /// Actual original meter limits used by the native invocation.
    pub limits: quire_exact::ScalarLimits,
    /// Independently held original source bytes and revision reference.
    pub source: LockedSource,
    /// Original admitted package/context used for native preparation.
    pub package: CheckedPackageV2,
    /// Actual emitted oracle outcome. No occurrence-pair count is invented from this Boolean.
    pub outcome: quire_exact::Outcome<bool>,
}

impl OriginalCompositeArtifactBinding {
    /// Retained original full positional body. Mutations are checked independently of identity.
    pub fn body(&self) -> &ParityPreimage {
        self.request.preimage()
    }
    /// Original emitted artifact set, for the driver to stage and independently capture after execution.
    pub fn artifacts(&self) -> &[Artifact] {
        &self.origin.artifacts
    }
    /// The selected original generated oracle entry, not a caller-supplied symbol.
    pub fn oracle_symbol(&self) -> &str {
        &self.oracle_symbol
    }
    /// The matching original prepared environment entry.
    pub fn environment_symbol(&self) -> &str {
        &self.environment_symbol
    }
    /// Ordered original operand values for the independent driver.
    pub fn operands(&self) -> &[WitnessValue; 2] {
        &self.operands
    }
    /// Original limits the driver must install.
    pub fn limits(&self) -> quire_exact::ScalarLimits {
        self.inputs.accounting_limits
    }
    /// Validate actual native context and staged bytes against the immutable generation/body.
    /// This produces no QSL falsified evidence or terminal settlement. A native Boolean cannot
    /// supply the pair count or backend success still owned by IR-806.
    ///
    /// # Errors
    /// Refuses any changed body, generated byte, operand, source/context or original limit.
    pub fn complete(
        self,
        body: &ParityPreimage,
        observed: CompositeDriverObservation,
    ) -> Result<AuthenticatedCompositeArtifact, CompositeBuildError> {
        if body != self.request.preimage() {
            return Err(CompositeBuildError::RetainedBodyMismatch);
        }
        let mut actual = observed.staged_entries;
        actual.sort_by(|left, right| left.0.cmp(&right.0));
        let mut original = self
            .origin
            .artifacts
            .iter()
            .map(|artifact| (artifact.path.clone(), artifact.contents.as_bytes().to_vec()))
            .collect::<Vec<_>>();
        original.sort_by(|left, right| left.0.cmp(&right.0));
        if actual != original
            || observed.oracle_symbol != self.oracle_symbol
            || observed.environment_symbol != self.environment_symbol
            || observed.operands != self.operands
            || observed.limits != self.inputs.accounting_limits
            || observed.source != self.inputs.source
            || observed.package != *self.origin.original
        {
            return Err(CompositeBuildError::GeneratedArtifactChanged);
        }
        Ok(AuthenticatedCompositeArtifact {
            request: self.request,
            outcome: observed.outcome,
            replay_limits: self.inputs.replay_limits,
        })
    }
}

/// Checked native artifact/context evidence only. Its outcome is not proof or QSL shadow evidence.
#[derive(Debug)]
pub struct AuthenticatedCompositeArtifact {
    request: OriginalCompositeEqRequest,
    outcome: quire_exact::Outcome<bool>,
    replay_limits: ReplayLimits,
}
impl AuthenticatedCompositeArtifact {
    /// Actual native outcome without an invented pair count.
    pub fn native_outcome(&self) -> &quire_exact::Outcome<bool> {
        &self.outcome
    }
    /// Original request for a driver's independent genuine facade call.
    pub fn request(&self) -> (ReplayRequestWire, CompositeParityClaim, ReplayLimits) {
        (
            self.request.wire().clone(),
            self.request.claim().clone(),
            self.replay_limits,
        )
    }
    /// Independently check the actual facade dispatch context. This authenticates no backend
    /// proof and creates no settlement; IR-806 owns the complete falsified conversion pipeline.
    /// # Errors
    /// Changed source/package/function/dependency, option, budget or other wire member refuses.
    pub fn check_sent_context(
        &self,
        actual_wire: &ReplayRequestWire,
        actual_limits: ReplayLimits,
    ) -> Result<(), CompositeBuildError> {
        if actual_limits != self.replay_limits
            || !super::scalar_builder::same_wire(actual_wire, self.request.wire())
        {
            return Err(CompositeBuildError::ContextMismatch);
        }
        Ok(())
    }
}
