/// Versioned format of the V2 clause observation report.
pub const V2_COVERAGE_FORMAT: &str = "codegen.v2-clause-coverage-observations/v1";
/// Strict schema for the V2 clause observation report.
pub const V2_COVERAGE_SCHEMA: &str =
    include_str!("../../schemas/v2-clause-coverage-observations-v1.schema.json");

/// Exact generated bytes and optional coverage for one checked V2 clause.
///
/// Each oracle currently emits `src/lib.rs`, so every input has its own source root and LLVM
/// export. The source, map and export are still unauthenticated until a producer receipt binds
/// them to one run.
pub struct V2ClauseCoverageInput<'a> {
    /// Clause node in the admitted checked package.
    pub node_id: &'a CheckedNodeId,
    /// Absolute lexical package root used by the LLVM export.
    pub source_root: &'a str,
    /// Exact generated Rust source bytes.
    pub source: &'a [u8],
    /// Exact JSON source-map bytes.
    pub source_map: &'a [u8],
    /// Exact LLVM export bytes, if the producer supplied them.
    pub llvm_export: Option<&'a [u8]>,
}

#[derive(Serialize)]
struct ConsequentObservation {
    ordinal: usize,
    count: Option<u64>,
}

#[derive(Serialize)]
struct ClauseObservation {
    identity: CheckedNodeId,
    expected_consequents: u32,
    evaluation_count: Option<u64>,
    consequents: Vec<ConsequentObservation>,
    classification: Option<ClauseCoverage>,
    diagnostics: Vec<CoverageDiagnostic>,
}

#[derive(Serialize)]
struct AnalysisBody {
    format: &'static str,
    state: BoundAnalysisState,
    population: &'static str,
    clauses: Vec<ClauseObservation>,
    diagnostics: Vec<CoverageDiagnostic>,
}

/// Bounded, unqualified V2 LLVM observations.
pub struct V2CoverageAnalysis(AnalysisBody);

impl V2CoverageAnalysis {
    /// Domain computation state; it does not authenticate a producer or grant proof credit.
    #[must_use]
    pub fn state(&self) -> BoundAnalysisState {
        self.0.state
    }

    /// Deterministic bounded JSON report of the observations and refusals.
    pub fn to_json_bytes(&self) -> Result<Vec<u8>, CoverageDiagnostic> {
        check_output_size(&self.0, MAX_ANALYSIS_BYTES)?;
        let bytes = serde_json::to_vec(&self.0).map_err(|_| {
            diagnostic(
                CoverageErrorCode::MalformedExport,
                "analysis serialization failed",
            )
        })?;
        if bytes.len() > MAX_ANALYSIS_BYTES {
            return Err(diagnostic(
                CoverageErrorCode::ResourceLimitExceeded,
                "analysis output exceeds 16 MiB",
            ));
        }
        Ok(bytes)
    }
}

fn diagnostic(code: CoverageErrorCode, message: impl Into<String>) -> CoverageDiagnostic {
    CoverageDiagnostic {
        code,
        message: message.into(),
    }
}

/// Analyze the complete executable V2 clause population against exact generated source/map
/// bytes and bounded LLVM entry probes. No native-run or proof verdict is produced.
pub fn analyze_v2_llvm_coverage(
    package: &CheckedPackageV2,
    inputs: &[V2ClauseCoverageInput<'_>],
) -> V2CoverageAnalysis {
    let mut body = AnalysisBody {
        format: V2_COVERAGE_FORMAT,
        state: BoundAnalysisState::InvalidInput,
        population: "not_emitted",
        clauses: Vec::new(),
        diagnostics: Vec::new(),
    };
    if let Err(error) = analyze_inner(package, inputs, &mut body) {
        body.state = match error.code {
            CoverageErrorCode::UnsupportedProfile | CoverageErrorCode::ResourceLimitExceeded => {
                BoundAnalysisState::Unsupported
            }
            _ => BoundAnalysisState::InvalidInput,
        };
        body.population = "not_emitted";
        body.clauses.clear();
        body.diagnostics.push(error);
    }
    if check_output_size(&body, MAX_ANALYSIS_BYTES).is_err() {
        body.state = BoundAnalysisState::Unsupported;
        body.population = "not_emitted";
        body.clauses.clear();
        body.diagnostics.clear();
        body.diagnostics.push(diagnostic(
            CoverageErrorCode::ResourceLimitExceeded,
            "analysis output exceeds 16 MiB; no observations classified",
        ));
    }
    V2CoverageAnalysis(body)
}

fn analyze_inner(
    package: &CheckedPackageV2,
    inputs: &[V2ClauseCoverageInput<'_>],
    body: &mut AnalysisBody,
) -> Result<(), CoverageDiagnostic> {
    let clauses: Vec<_> = package
        .graph()
        .nodes
        .iter()
        .filter(|node| &*node.node_tag == "state" && &*node.semantic_form == "state_clause")
        .map(|node| &node.node_id)
        .collect();
    if clauses.len() > MAX_ARTIFACTS / 2 || inputs.len() > MAX_ARTIFACTS / 2 {
        return Err(diagnostic(
            CoverageErrorCode::ResourceLimitExceeded,
            "clause artifact count exceeded",
        ));
    }
    if clauses.is_empty() {
        if !inputs.is_empty() {
            return Err(diagnostic(
                CoverageErrorCode::PopulationMismatch,
                "empty checked clause population has supplied artifacts",
            ));
        }
        body.state = BoundAnalysisState::NoExecutable;
        body.population = "complete";
        return Ok(());
    }
    if inputs.len() != clauses.len() {
        return Err(diagnostic(
            CoverageErrorCode::PopulationMismatch,
            "complete checked clause artifact population required",
        ));
    }
    let mut by_id = BTreeMap::new();
    let mut total_bytes = 0usize;
    for input in inputs {
        if by_id.insert(input.node_id, input).is_some() {
            return Err(diagnostic(
                CoverageErrorCode::PopulationMismatch,
                "duplicate checked clause artifact identity",
            ));
        }
        if input.source_root.len() > MAX_SOURCE_ROOT_BYTES
            || input.source.len() > MAX_ARTIFACT_BYTES
            || input.source_map.len() > MAX_ARTIFACT_BYTES
            || input
                .llvm_export
                .is_some_and(|bytes| bytes.len() > MAX_COVERAGE_BYTES)
        {
            return Err(diagnostic(
                CoverageErrorCode::ResourceLimitExceeded,
                "V2 artifact or coverage byte budget exceeded",
            ));
        }
        total_bytes = total_bytes.saturating_add(input.source.len());
        total_bytes = total_bytes.saturating_add(input.source_map.len());
        total_bytes = total_bytes.saturating_add(input.llvm_export.map_or(0, |bytes| bytes.len()));
        if total_bytes > MAX_BUNDLE_BYTES {
            return Err(diagnostic(
                CoverageErrorCode::ResourceLimitExceeded,
                "V2 artifact and coverage byte budget exceeded",
            ));
        }
    }
    let expected: BTreeSet<_> = clauses.iter().copied().collect();
    if by_id.keys().copied().collect::<BTreeSet<_>>() != expected {
        return Err(diagnostic(
            CoverageErrorCode::PopulationMismatch,
            "supplied clause identities differ from checked population",
        ));
    }
    body.population = "complete";
    body.state = BoundAnalysisState::Complete;
    for node_id in clauses {
        let input = by_id[&node_id];
        let root = normalize_path(input.source_root)?;
        if !root.starts_with('/') || root == "/" {
            return Err(diagnostic(
                CoverageErrorCode::InvalidPath,
                "source root must be an absolute package directory",
            ));
        }
        let descriptor = derive_v2_clause_descriptor(package, node_id).map_err(|error| {
            diagnostic(
                CoverageErrorCode::PopulationMismatch,
                format!("checked clause {node_id:?} could not be described: {error:?}"),
            )
        })?;
        let generated = generate_v2_clause_oracle(package, node_id).map_err(|error| {
            diagnostic(
                CoverageErrorCode::PopulationMismatch,
                format!("checked clause {node_id:?} could not be generated: {error:?}"),
            )
        })?;
        if input.source != generated.source.as_bytes() {
            return Err(diagnostic(
                CoverageErrorCode::ArtifactMismatch,
                format!("checked clause {node_id:?} generated source bytes differ"),
            ));
        }
        let map: Vec<V2ClauseCoverageRegion> =
            serde_json::from_slice(input.source_map).map_err(|_| {
                diagnostic(
                    CoverageErrorCode::MapMismatch,
                    format!("checked clause {node_id:?} source map is malformed"),
                )
            })?;
        check_map(
            node_id,
            descriptor.expected_consequents,
            &map,
            &generated.source_map,
        )?;
        let generated_map = serde_json::to_vec(&generated.source_map).map_err(|_| {
            diagnostic(
                CoverageErrorCode::MapMismatch,
                format!("checked clause {node_id:?} generated map serialization failed"),
            )
        })?;
        if input.source_map != generated_map {
            return Err(diagnostic(
                CoverageErrorCode::MapMismatch,
                format!("checked clause {node_id:?} source map bytes differ from generation"),
            ));
        }
        let coverage = input
            .llvm_export
            .map(|bytes| parse_llvm_coverage(bytes, &root))
            .transpose()?;
        if coverage.as_ref().is_some_and(|coverage| {
            coverage
                .paths()
                .any(|path| path.starts_with("src/") && path != "src/lib.rs")
        }) {
            return Err(diagnostic(
                CoverageErrorCode::ForeignGeneratedFile,
                format!("checked clause {node_id:?} LLVM export names a foreign generated source"),
            ));
        }
        let row = observe_clause(
            node_id,
            descriptor.expected_consequents,
            &map,
            coverage.as_ref(),
        );
        if row.classification.is_none() {
            body.state = BoundAnalysisState::Incomplete;
        }
        body.clauses.push(row);
    }
    Ok(())
}

fn check_map(
    node_id: &CheckedNodeId,
    count: u32,
    map: &[V2ClauseCoverageRegion],
    generated: &[V2ClauseCoverageRegion],
) -> Result<(), CoverageDiagnostic> {
    let mismatched = || {
        diagnostic(
            CoverageErrorCode::MapMismatch,
            format!(
                "checked clause {node_id:?} source map differs from admitted body and generation"
            ),
        )
    };
    let length = usize::try_from(count)
        .map_err(|_| mismatched())?
        .saturating_add(1);
    if map.len() != length
        || map.first().and_then(|region| region.expected_consequents) != Some(count)
        || map != generated
    {
        return Err(mismatched());
    }
    Ok(())
}

fn observe_clause(
    node_id: &CheckedNodeId,
    count: u32,
    map: &[V2ClauseCoverageRegion],
    coverage: Option<&LlvmCoverage>,
) -> ClauseObservation {
    let mut row = ClauseObservation {
        identity: node_id.clone(),
        expected_consequents: count,
        evaluation_count: None,
        consequents: Vec::new(),
        classification: None,
        diagnostics: Vec::new(),
    };
    let observe =
        |region: &V2ClauseCoverageRegion| -> Result<ProbeObservation, CoverageDiagnostic> {
            let coverage = coverage.ok_or_else(|| {
                diagnostic(
                    CoverageErrorCode::UnavailableObservation,
                    "LLVM export was not supplied",
                )
            })?;
            coverage.observe(&region.artifact_path, region.probe)
        };
    let [entry, consequents @ ..] = map else {
        row.diagnostics.push(diagnostic(
            CoverageErrorCode::MapMismatch,
            "missing evaluation probe",
        ));
        return row;
    };
    let evaluation = observe(entry);
    match &evaluation {
        Ok(value) => row.evaluation_count = Some(value.count()),
        Err(error) => row.diagnostics.push(error.clone()),
    }
    let mut observed = Vec::new();
    for (ordinal, region) in consequents.iter().enumerate() {
        let count = match observe(region) {
            Ok(value) => {
                observed.push(value);
                Some(value.count())
            }
            Err(error) => {
                row.diagnostics.push(error);
                None
            }
        };
        row.consequents
            .push(ConsequentObservation { ordinal, count });
    }
    if let Ok(evaluation) = &evaluation {
        if observed
            .iter()
            .any(|probe| probe.count() > evaluation.count())
        {
            row.diagnostics.push(diagnostic(
                CoverageErrorCode::InconsistentObservation,
                "consequent count exceeds generated oracle evaluation count",
            ));
        }
    }
    if let (Ok(evaluation), true) = (evaluation, row.diagnostics.is_empty()) {
        match classify_clause(evaluation, count, &observed) {
            Ok(classification) => row.classification = Some(classification),
            Err(error) => row.diagnostics.push(error),
        }
    }
    row
}

