//! Source rendering for concrete FR-485 function bodies.

#[cfg(test)]
use super::ExactFunctionDeclaration;
use super::{
    BinaryIntegerOperator, CheckedNodeId, ClassifiedBody, ClassifiedFunction, EqualityOperatorKind,
    ExactFunctionRefusal, FunctionNames, FunctionSourceIndex, GraphBody,
};

/// The body forms the direct renderer can emit before nested call-site provenance lands.
#[cfg(test)]
pub(super) enum DirectBody {
    Scalar(BinaryIntegerOperator),
    Equality(EqualityOperatorKind),
}

/// Resolve the callable declaration in the admitted graph before rendering a direct body.
/// A body-expression ID alone is never a QSL callable key.
#[cfg(test)]
pub(super) fn checked_item<Body: GraphBody>(
    index: &FunctionSourceIndex<'_, Body>,
    symbol: &str,
    declaration: &ExactFunctionDeclaration,
    body: DirectBody,
) -> Result<String, ExactFunctionRefusal> {
    let callable = index
        .source_function_node_id(&declaration.name, &declaration.node_id)
        .ok_or(ExactFunctionRefusal::BodyMismatch)?;
    match body {
        DirectBody::Scalar(operator) => Ok(scalar_item(symbol, callable, operator)),
        DirectBody::Equality(operator) => Ok(equality_item(symbol, callable, operator)),
    }
}

/// Render a survivor from its admitted callable and body identities.
pub(super) fn classified_item<Body: GraphBody>(
    index: &FunctionSourceIndex<'_, Body>,
    names: &FunctionNames<'_>,
    symbol: &str,
    function: &ClassifiedFunction<'_>,
) -> Result<String, ExactFunctionRefusal> {
    let declaration = function.declaration;
    let caller = index
        .source_function_node_id(&declaration.name, &declaration.node_id)
        .ok_or(ExactFunctionRefusal::BodyMismatch)?;
    match &function.body {
        ClassifiedBody::Scalar(operator) => Ok(scalar_item(symbol, caller, *operator)),
        ClassifiedBody::Equality(operator) => Ok(equality_item(symbol, caller, *operator)),
        ClassifiedBody::Call(callee) => {
            let callee_body = names.unique_node_id(callee).ok_or_else(|| {
                ExactFunctionRefusal::UnknownCallee {
                    callee: (*callee).to_owned(),
                }
            })?;
            let callee_function = index
                .source_function_node_id(callee, callee_body)
                .ok_or(ExactFunctionRefusal::BodyMismatch)?;
            Ok(call_item(
                symbol,
                caller,
                callee_function,
                &function.body_node_id,
            ))
        }
    }
}

pub(super) const HEADER: &str = r#"// @generated by quire-contract-codegen. Do not edit.
use quire_contract_codegen::{
    apply_checked_function, select_checked_callable, selected_nested_call_site,
    CheckedFunctionError, CheckedFunctionSource,
};
use quire_contract_model::{CheckedNodeId, CheckedPackageV2};
use quire_eval::{self as eval, Body, BodyFactory, ChildRequest, FamilyOutcome, Resume, Transition};
use quire_exact::{self as exact, Meter, Outcome, Refusal, Value};
use quire_semantic_value::{self as sv, object_closure::ObjectClosure};

fn evaluated(outcome: Outcome<Value>) -> eval::Evaluation {
    eval::Evaluation { outcome: FamilyOutcome::Evaluated(outcome), location: None, losses: Vec::new() }
}
"#;

/// Render an own-package scalar body through the generated-body registration path.
pub(super) fn scalar_item(
    symbol: &str,
    function: &CheckedNodeId,
    operator: BinaryIntegerOperator,
) -> String {
    let variant = operator.variant();
    let body = format!(
        r#"let [Value::Integer(left), Value::Integer(right)] = args.as_slice() else {{
    return Outcome::Refused(Refusal::CheckedInvariant {{
        cause: exact::CheckedInvariantCause::GeneratedArgumentShapeMismatch,
    }});
}};
match exact::evaluate_integer_arithmetic(exact::IntegerArithmetic::{variant}(left, right), None, meter) {{
    Outcome::Completed(value) => Outcome::Completed(Value::Integer(value)),
    Outcome::Undefined(value) => Outcome::Undefined(value),
    Outcome::Refused(value) => Outcome::Refused(value),
    Outcome::Incomplete(value) => Outcome::Incomplete(value),
}}"#
    );
    render_item(symbol, function, &body)
}

/// Render an own-package Boolean or Integer equality body over the QSV leaf.
pub(super) fn equality_item(
    symbol: &str,
    function: &CheckedNodeId,
    operator: EqualityOperatorKind,
) -> String {
    let variant = match operator {
        EqualityOperatorKind::Equal => "Equal",
        EqualityOperatorKind::NotEqual => "NotEqual",
    };
    let body = format!(
        r#"let [left, right] = args.as_slice() else {{
    return Outcome::Refused(Refusal::CheckedInvariant {{
        cause: exact::CheckedInvariantCause::GeneratedArgumentShapeMismatch,
    }});
}};
let operand_type = match left {{
    Value::Boolean(_) => exact::ValueType::Boolean,
    Value::Integer(_) => exact::ValueType::Integer,
    _ => return Outcome::Refused(Refusal::CheckedInvariant {{
        cause: exact::CheckedInvariantCause::GeneratedOperandKindUnsupported,
    }}),
}};
let environment = sv::declaration::TypeEnvironment::default();
let checked = match environment.check_equality(
    sv::declaration::EqualityOperator::{variant},
    sv::declaration::EqualityOperand::typed(operand_type.clone()),
    sv::declaration::EqualityOperand::typed(operand_type),
    &sv::enumeration::EnumMemberIndex::default(),
) {{
    Ok(checked) => checked,
    Err(error) => return Outcome::Refused(Refusal::CheckedInvariant {{
        cause: exact::CheckedInvariantCause::GeneratedEqualityCheckRejected {{ cause: error.cause }},
    }}),
}};
match checked.evaluate(&environment, left, right, meter) {{
    Outcome::Completed(value) => Outcome::Completed(Value::Boolean(value)),
    Outcome::Undefined(value) => Outcome::Undefined(value),
    Outcome::Refused(value) => Outcome::Refused(value),
    Outcome::Incomplete(value) => Outcome::Incomplete(value),
}}"#
    );
    render_item(symbol, function, &body)
}

fn render_item(symbol: &str, function: &CheckedNodeId, body: &str) -> String {
    format!(
        r#"
mod body_{symbol} {{
    use super::*;
    pub(super) struct Factory;
    impl BodyFactory for Factory {{
        fn begin(&self) -> Box<dyn Body> {{ Box::new(Invocation) }}
    }}
    struct Invocation;
    impl Body for Invocation {{
        fn resume(&mut self, input: Resume, meter: &mut Meter)
            -> Result<Transition, sv::catalog::InternalFault>
        {{
            match input {{
                Resume::Start(args) => Ok(Transition::Done(evaluated(run(args, meter)))),
                Resume::Again | Resume::Child(_) =>
                    Err(sv::catalog::InternalFault::new("generated_function", "unexpected_resume")),
            }}
        }}
    }}
    fn run(args: Vec<Value>, meter: &mut Meter) -> Outcome<Value> {{
        {body}
    }}
}}

/// Apply this generated body to the caller's separately admitted checked unit.
pub fn oracle_{symbol}(
    source: CheckedFunctionSource<'_>,
    admitted_unit: &CheckedPackageV2,
    declaring_package: &CheckedPackageV2,
    arguments: Vec<Value>,
    objects: ObjectClosure,
    meter: &mut Meter,
) -> Result<Result<eval::Evaluation, eval::CallFailure>, CheckedFunctionError> {{
    let function = CheckedNodeId {{
        domain: {domain:?}.into(),
        digest: {digest:?}.into(),
    }};
    apply_checked_function(
        source, admitted_unit, declaring_package, &function, arguments, objects, meter,
        |_, _| Ok(body_{symbol}::Factory),
    )
}}
"#,
        domain = function.domain,
        digest = function.digest,
    )
}

/// Render one checked nested call through the leaf scheduler. The caller and
/// callee selections and the call site all come from the same QSL acquisition.
pub(super) fn call_item(
    symbol: &str,
    caller: &CheckedNodeId,
    callee: &CheckedNodeId,
    call: &CheckedNodeId,
) -> String {
    format!(
        r#"
mod body_{symbol} {{
    use super::*;
    pub(super) struct Factory {{
        callee: exact::NodeKey,
        site: sv::location::Location,
    }}
    impl Factory {{
        pub(super) fn new(callee: exact::NodeKey, site: sv::location::Location) -> Self {{
            Self {{ callee, site }}
        }}
    }}
    impl BodyFactory for Factory {{
        fn begin(&self) -> Box<dyn Body> {{
            Box::new(Invocation {{ callee: self.callee, site: self.site.clone() }})
        }}
    }}
    struct Invocation {{
        callee: exact::NodeKey,
        site: sv::location::Location,
    }}
    impl Body for Invocation {{
        fn resume(&mut self, input: Resume, _meter: &mut Meter)
            -> Result<Transition, sv::catalog::InternalFault>
        {{
            match input {{
                Resume::Start(arguments) => Ok(Transition::Call(ChildRequest {{
                    callee: self.callee,
                    arguments,
                    site: self.site.clone(),
                }})),
                Resume::Child(result) => Ok(Transition::Done(result)),
                Resume::Again => Err(sv::catalog::InternalFault::new(
                    "generated_function", "unexpected_resume",
                )),
            }}
        }}
    }}
}}

/// Apply a selected caller with one nested call through its checked site.
pub fn oracle_{symbol}(
    source: CheckedFunctionSource<'_>,
    admitted_unit: &CheckedPackageV2,
    declaring_package: &CheckedPackageV2,
    callee_package: &CheckedPackageV2,
    arguments: Vec<Value>,
    objects: ObjectClosure,
    meter: &mut Meter,
) -> Result<Result<eval::Evaluation, eval::CallFailure>, CheckedFunctionError> {{
    let caller = CheckedNodeId {{
        domain: {caller_domain:?}.into(), digest: {caller_digest:?}.into(),
    }};
    let callee = CheckedNodeId {{
        domain: {callee_domain:?}.into(), digest: {callee_digest:?}.into(),
    }};
    let call = CheckedNodeId {{
        domain: {call_domain:?}.into(), digest: {call_digest:?}.into(),
    }};
    apply_checked_function(
        source, admitted_unit, declaring_package, &caller, arguments, objects, meter,
        |handle, selection| {{
            let callee_selection =
                select_checked_callable(admitted_unit, callee_package, &callee, handle)?;
            let site =
                selected_nested_call_site(declaring_package, &call, handle, selection)?;
            Ok(body_{symbol}::Factory::new(
                callee_selection.key(), site.location().clone(),
            ))
        }},
    )
}}
"#,
        caller_domain = caller.domain,
        caller_digest = caller.digest,
        callee_domain = callee.domain,
        callee_digest = callee.digest,
        call_domain = call.domain,
        call_digest = call.digest,
    )
}

