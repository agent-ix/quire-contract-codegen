//! Headers for generated Rust, built only from identities carried by generation inputs.

use std::fmt::Write;

/// Adds generator, licensing and supplied subject identities to one emitted Rust source.
pub(crate) fn with_rust_header<'a>(
    source: String,
    subjects: impl IntoIterator<Item = &'a str>,
) -> String {
    let mut header = String::from("// SPDX-License-Identifier: MIT OR Apache-2.0\n// @generated by quire-contract-codegen. Do not edit.\n");
    for subject in subjects {
        let _ = writeln!(header, "// Subject: {subject}");
    }
    header.push('\n');
    let source = source
        .strip_prefix("// SPDX-License-Identifier: MIT OR Apache-2.0\n")
        .unwrap_or(&source);
    header.push_str(source);
    header
}
