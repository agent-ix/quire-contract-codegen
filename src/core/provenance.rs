//! Headers for generated Rust, built only from identities carried by generation inputs.

use quire_contract_model::CheckedNodeId;
use std::fmt::Write;

const RUST_HEADER_PREFIX: &str = "// SPDX-License-Identifier: MIT OR Apache-2.0\n// @generated by quire-contract-codegen. Do not edit.\n";

/// Stable, input-carried identity for a checked semantic node.
pub(crate) fn node_subject(id: &CheckedNodeId) -> String {
    format!("{}/{}", id.domain, id.digest)
}

/// Adds generator, licensing and supplied subject identities to one emitted Rust source.
pub(crate) fn with_rust_header<'a>(
    source: String,
    subjects: impl IntoIterator<Item = &'a str>,
) -> String {
    let mut header = String::from(RUST_HEADER_PREFIX);
    for subject in subjects {
        let _ = writeln!(header, "// Subject: {}", subject.escape_debug());
    }
    header.push('\n');
    let source = source
        .strip_prefix("// SPDX-License-Identifier: MIT OR Apache-2.0\n")
        .unwrap_or(&source);
    header.push_str(source);
    header
}

/// Return the body of a Rust source emitted by [`with_rust_header`].
pub(crate) fn rust_body(source: &str) -> Option<&str> {
    source
        .strip_prefix(RUST_HEADER_PREFIX)?
        .split_once("\n\n")
        .map(|(_, body)| body)
}

#[cfg(test)]
mod tests {
    use super::with_rust_header;
    use ix_trace_rs::trace;

    #[trace("TC-001", "NFR-002-AC-1")]
    #[test]
    fn newline_in_subject_stays_inside_header_comment() {
        let source = with_rust_header(
            "pub fn safe() {}\n".to_owned(),
            ["deposit\npub fn injected() {}"],
        );
        let header = source.split("\n\n").next().expect("header");
        assert!(header.lines().all(|line| line.starts_with("// ")));
        assert!(!source.lines().any(|line| line == "pub fn injected() {}"));
        syn::parse_file(&source).expect("generated Rust parses");
    }
}
