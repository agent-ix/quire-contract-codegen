//! Render the selected Boolean proposition and its independent expectation root.

use crate::{
    core::artifact::{Artifact, MAX_GENERATED_SOURCE_BYTES},
    kani::{
        generate::{outcome::UnsupportedObligation, record::record},
        identity::state_transition::{KaniStateTransitionHarness, StateTransitionIdentity},
    },
};

pub(in crate::kani::generate) fn render(
    identity: StateTransitionIdentity,
) -> Result<KaniStateTransitionHarness, UnsupportedObligation> {
    let source = format!(
        "// SPDX-License-Identifier: MIT OR Apache-2.0\n\
// @generated by quire-contract-codegen. Do not edit.\n\
#[cfg(kani)]\n\
mod {module} {{\n\
use super::*;\n\
#[inline(never)]\n\
fn subject_boolean_state_transition(input_current: bool, state_pre: bool) -> bool {{\n\
let mut state_post = state_pre;\n\
{subject}(input_current, &mut state_post);\n\
state_post\n\
}}\n\
#[inline(never)]\n\
fn expected_boolean_state_transition(input_current: bool, state_pre: bool) -> bool {{\n\
input_current || state_pre\n\
}}\n\
#[kani::proof]\n\
#[kani::unwind({unwind})]\n\
fn {proof}() {{\n\
let input_current: bool = kani::any();\n\
let state_pre: bool = kani::any();\n\
kani::assume(input_current || state_pre);\n\
let state_post = subject_boolean_state_transition(input_current, state_pre);\n\
assert!(state_post, \"Boolean field-transition postcondition\");\n\
assert!(state_post == expected_boolean_state_transition(input_current, state_pre), \"independent Boolean field-transition model\");\n\
kani::cover!(state_post, \"Boolean field-transition non-vacuity\");\n\
}}\n\
}}\n",
        module = identity.module_symbol,
        subject = identity.subject_path,
        unwind = identity.unwind,
        proof = identity.harness_symbol,
    );
    if source.len() > MAX_GENERATED_SOURCE_BYTES {
        return Err(UnsupportedObligation::ResourceLimitExceeded {
            bytes: source.len(),
        });
    }
    syn::parse_file(&source).map_err(|error| UnsupportedObligation::InvalidGeneratedSyntax {
        error: error.to_string(),
    })?;
    let rust = Artifact::new(
        format!("src/generated/{}.rs", identity.module_symbol),
        source,
    );
    let record = record(identity.module_symbol.as_str(), &identity, &rust)?;
    Ok(KaniStateTransitionHarness {
        identity,
        rust,
        record,
    })
}
